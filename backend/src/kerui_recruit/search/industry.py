def normalize_industry(value: str | None) -> frozenset[str]:
    """把单个行业字符串归一为规范桶集合（子串包含，casefold）。"""
    if not value:
        return frozenset()
    folded = value.strip().casefold()
    if not folded:
        return frozenset()
    buckets: set[str] = set()
    for canonical, aliases in INDUSTRY_BUCKETS.items():
        for alias in aliases:
            if alias.casefold() in folded:
                buckets.add(canonical)
                break
    return frozenset(buckets)


def normalize_industries(values: list[str | None]) -> frozenset[str]:
    """合并多个行业字段（industry / current_industry / longest_industry）的桶。"""
    buckets: set[str] = set()
    for value in values:
        buckets.update(normalize_industry(value))
    return frozenset(buckets)
