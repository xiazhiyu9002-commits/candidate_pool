def _qs_band(rank: int) -> str:
    """把 QS 排名映射到学校等级区间。"""
    if rank <= 50:
        return "前50"
    if rank <= 100:
        return "前100"
    if rank <= 150:
        return "前150"
    if rank <= 200:
        return "前200"
    if rank <= 300:
        return "前300"
    return "300后"


