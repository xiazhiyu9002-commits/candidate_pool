def seed_schools(session: Session) -> int:
    """把内置 985/211/双一流 名录写入 school 表（幂等，按标准名跳过已存在）。"""
    seeds = [
        (SEED_985, ["985", "211", "双一流"]),
        (SEED_211, ["211", "双一流"]),
        (SEED_DOUBLE_FIRST_CLASS, ["双一流"]),
    ]
    seeded = 0
    for names, tags in seeds:
        for name in names:
            existing = session.scalars(
                select(School).where(School.canonical_name == name)
            ).first()
            aliases = SCHOOL_ALIASES.get(name)
            if existing is not None:
                # 幂等补充内置别名，不覆盖用户导入的别名。
                if aliases and not existing.aliases:
                    existing.aliases = sorted(aliases)
                continue
            session.add(
                School(
                    canonical_name=name,
                    normalized_name=normalize_school_name(name) or name,
                    aliases=sorted(aliases) if aliases else None,
                    tags=tags,
                    institution_type="本科院校",
                    source="builtin",
                )
            )
            seeded += 1

    for name, aliases, country, rank in SEED_OVERSEAS_QS:
        existing = session.scalars(
            select(School).where(School.canonical_name == name)
        ).first()
        if existing is not None:
            if aliases and not existing.aliases:
                existing.aliases = sorted(aliases)
            if existing.qs_rank_start is None:
                existing.qs_year = 2026
                existing.qs_rank_start = rank
                existing.rank_display = _qs_band(rank)
            continue
        session.add(
            School(
                canonical_name=name,
                normalized_name=normalize_school_name(name) or name,
                aliases=sorted(aliases) if aliases else None,
                country_region=country,
                institution_type="海外院校",
                tags=["海外"],
                qs_year=2026,
                qs_rank_start=rank,
                rank_display=_qs_band(rank),
                source="builtin",
            )
        )
        seeded += 1
    return seeded
